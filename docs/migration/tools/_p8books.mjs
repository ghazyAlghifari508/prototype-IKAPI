import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
p.on('pageerror', (e) => console.log('ERR', String(e).slice(0, 140)));
await p.goto('http://127.0.0.1:8140/penerbit/buku', { waitUntil: 'load' });
await p.waitForTimeout(600);
const stat = async (label) => console.log(label, await p.evaluate(() => ({ rows: [...document.querySelectorAll('#book-rows tr[data-id]')].filter((r) => r.offsetParent !== null).length, total: document.querySelectorAll('#book-rows tr[data-id]').length, note: document.querySelector('[id*="result"], [id*="count"], .page-note')?.textContent.replace(/\s+/g, ' ').trim().slice(0, 40) })));
await stat('initial');
await p.fill('#book-search', 'laskar');
await p.waitForTimeout(400);
await stat('after fill');
await p.type('#book-search', ' ');
await p.waitForTimeout(400);
await stat('after type');
await p.fill('#book-search', '');
await p.click('[data-filter="draft"]');
await p.waitForTimeout(400);
await stat('after draft chip');
await p.click('[data-filter="all"]');
await p.waitForTimeout(300);
await stat('after all');
await b.close();
