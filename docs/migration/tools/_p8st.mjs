import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
p.on('pageerror', (e) => console.log('ERR', (e.stack || String(e)).split('\n').slice(0, 3).join(' | ')));
await p.goto('http://127.0.0.1:8140/penerbit/pengaturan', { waitUntil: 'load' });
await p.waitForTimeout(600);
console.log('ids:', await p.evaluate(() => ['profile-form','b-bank','bank-form','btn-bank-edit','modal-bank-confirm','btn-bank-review'].map((id) => id + '=' + !!document.getElementById(id)).join(' ')));
console.log('sections:', await p.evaluate(() => [...document.querySelectorAll('[id^="view-"]')].map((e) => e.id + ':' + (e.classList.contains('hidden') ? 'hidden' : 'shown'))));
await b.close();
