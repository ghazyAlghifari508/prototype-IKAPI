import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:8140/penerbit/keuangan', { waitUntil: 'load' });
await p.waitForTimeout(500);
await p.fill('#input-nominal', '250000');
await p.check('#confirm-check').catch(() => {});
await p.click('#btn-review');
await p.waitForTimeout(400);
console.log('confirm buttons:', await p.evaluate(() => [...document.querySelectorAll('#modal-confirm button')].map((b) => [b.id || '-', b.className.slice(0, 20), b.textContent.replace(/\s+/g, ' ').trim()])));
console.log('confirm hidden?', await p.evaluate(() => document.getElementById('modal-confirm').className));
await p.click('#modal-confirm button:last-of-type').catch(() => {});
await p.waitForTimeout(700);
console.log('success class:', await p.evaluate(() => document.getElementById('modal-success')?.className));
console.log('main has success text:', await p.evaluate(() => document.body.innerText.includes('Pencairan') ));
await p.goto('http://127.0.0.1:8140/penerbit/ulasan', { waitUntil: 'load' });
await p.waitForTimeout(500);
console.log('review cards:', await p.evaluate(() => document.querySelectorAll('main article').length));
console.log('reply forms:', await p.evaluate(() => [...document.querySelectorAll('main article form')].map((f) => [f.id || '-', f.className.slice(0, 24), f.querySelector('textarea')?.className.slice(0, 20), [...f.querySelectorAll('button')].map((b) => b.textContent.trim())])));
await b.close();
