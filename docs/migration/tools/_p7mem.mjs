import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:8140/komunitas/community-filologi', { waitUntil: 'load' });
await p.waitForTimeout(600);
const join = p.locator('#profile-actions button', { hasText: /Gabung|Bergabung/i }).first();
if (await join.isVisible().catch(() => false)) await join.click();
await p.waitForTimeout(500);
console.log('memberships', await p.evaluate(() => localStorage.getItem('ikapi_community_memberships_demo')));
await p.goto('http://127.0.0.1:8140/komunitas/community-filologi/diskusi', { waitUntil: 'load' });
await p.waitForTimeout(700);
console.log('createEnabled', await p.locator('#btn-new-topic').isEnabled());
console.log('ids', await p.evaluate(() => [...document.querySelectorAll('#view-room [id]')].map((e) => e.id)));
await p.click('#btn-new-topic');
await p.waitForTimeout(300);
console.log('composer visible', await p.isVisible('#composer-modal'));
console.log('inputs', await p.evaluate(() => [...document.querySelectorAll('#composer-modal input, #composer-modal textarea')].map((e) => e.id)));
await b.close();
